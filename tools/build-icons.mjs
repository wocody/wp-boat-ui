// Generates src/icons.php from Heroicons v1 (MIT): outline 24px stroke icons and solid 20px icons.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules', 'heroicons');
const php = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

let out = "<?php\n/**\n * Heroicons v1.0.6 (MIT, https://github.com/tailwindlabs/heroicons). Generated by tools/build-icons.mjs.\n *\n * @package Wocody\\BoatUI\n */\n\nreturn array(\n";
for (const set of ['outline', 'solid']) {
	out += `\t'${set}' => array(\n`;
	for (const file of readdirSync(join(source, set)).filter((name) => name.endsWith('.svg')).sort()) {
		const svg = readFileSync(join(source, set, file), 'utf8');
		const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
		out += `\t\t${php(file.replace('.svg', ''))} => ${php(inner)},\n`;
	}
	out += '\t),\n';
}
out += ");\n";
writeFileSync(join(root, 'src', 'icons.php'), out);
console.log('src/icons.php written');
