// Generates src/icons.php from Phosphor Icons "regular" (MIT, https://phosphoricons.com): 256×256 fill icons.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');
const source = join(modules, '@phosphor-icons', 'core', 'assets', 'regular');
const php = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const version = JSON.parse(readFileSync(join(modules, '@phosphor-icons', 'core', 'package.json'), 'utf8')).version;

let out = `<?php\n/**\n * Phosphor Icons ${version}, regular weight (MIT, https://phosphoricons.com). Generated by tools/build-icons.mjs.\n *\n * @package Wocody\\BoatUI\n */\n\nreturn array(\n`;
let count = 0;
for (const file of readdirSync(source).filter((name) => name.endsWith('.svg')).sort()) {
	const svg = readFileSync(join(source, file), 'utf8');
	const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
	out += `\t${php(file.replace('.svg', ''))} => ${php(inner)},\n`;
	count++;
}
out += ');\n';
writeFileSync(join(root, 'src', 'icons.php'), out);

console.log(`src/icons.php written (${count} icons)`);
